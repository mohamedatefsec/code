const ORDINALS = [
  "الأولى",
  "الثانية",
  "الثالثة",
  "الرابعة",
  "الخامسة",
  "السادسة",
  "السابعة",
  "الثامنة",
  "التاسعة",
  "العاشرة",
  "الحادية عشرة",
  "الثانية عشرة",
];

/// اسم الوحدة حسب مكانها في الترتيب (index بيبدأ من 0):
/// "الوحدة الأولى"، "الوحدة الثانية"... وبعد الـ 12 بالرقم ("الوحدة 13").
export function unitLabel(index: number) {
  return `الوحدة ${ORDINALS[index] ?? index + 1}`;
}

